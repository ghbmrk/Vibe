void gfx_load_font(void) {
    uint8_t buf[16];
    uint8_t i, row;
    for (i = 0; i < FONT_CHARS; i++) {
        for (row = 0; row < 8; row++) {
            buf[row * 2]     = font_1bpp[(uint16_t)i * 8 + row];
            buf[row * 2 + 1] = font_1bpp[(uint16_t)i * 8 + row];
        }
        set_bkg_data(TILE_FONT_BASE + i, 1, buf);
    }
}

void gfx_load_terrain(void) {
    set_bkg_data(TILE_GRASS, NUM_TERRAIN_TILES, terrain_tiles);
}

void gfx_load_ui_tiles(void) {
    set_bkg_data(TILE_BLANK, NUM_UI_TILES, ui_tiles);
}

void gfx_load_player_sprite(void) {
    set_sprite_data(SPR_TILE_PLAYER_DOWN, 12, player_sprite);
}

void gfx_load_creature_sprite(uint8_t dest_tile, uint8_t species) {
    set_bkg_data(dest_tile, 16,
                 &creature_sprites[(uint16_t)species * 256]);
}

void gfx_set_overworld_palettes(void) {
    set_bkg_palette(0, 8, bg_palettes);
    set_sprite_palette(0, 2, sprite_palettes);
}

void gfx_set_battle_palettes(uint8_t player_elem, uint8_t enemy_elem) {
    uint16_t pal_buf[4];

    /* PAL 0 stays UI */
    /* Set PAL 1 for player creature */
    memcpy(pal_buf, &elem_palettes[(uint16_t)player_elem * 4], 8);
    set_bkg_palette(1, 1, pal_buf);

    /* Set PAL 2 for enemy creature */
    memcpy(pal_buf, &elem_palettes[(uint16_t)enemy_elem * 4], 8);
    set_bkg_palette(2, 1, pal_buf);
}
