/* =========================================================
   GFX INIT - Load all tiles and palettes into VRAM
   ========================================================= */
void gfx_init(void) {
    /* Load BG tiles */
    set_bkg_data(TILE_FONT_START, FONT_TILE_COUNT, font_tiles);
    set_bkg_data(TILE_UI_START, UI_TILE_COUNT, ui_tiles);
    set_bkg_data(TILE_TERRAIN_START, TERRAIN_TILE_COUNT, terrain_tiles);

    /* Load sprite tiles - player first, then creatures */
    set_sprite_data(0, PLAYER_TILE_COUNT, player_sprite);
    set_sprite_data(PLAYER_TILE_COUNT, CREATURE_TILE_COUNT, creature_sprites);

    /* Set CGB palettes */
    set_bkg_palette(0, 8, bg_palettes);
    set_sprite_palette(0, 8, obj_palettes);

    /* Show BG and sprites */
    SHOW_BKG;
    SHOW_SPRITES;
    SPRITES_8x8;
}
